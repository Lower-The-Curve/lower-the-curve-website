// Fragment for the `partners` metaobject that PartnersSection renders: resolves
// the list of partner items and each item's logo.
export const partnersSectionFragment = /* GraphQL */ `
  fragment PartnersSectionFields on Metaobject {
    id
    handle
    type
    fields {
      key
      type
      value
      references(first: 50) {
        nodes {
          __typename
          ... on Metaobject {
            id
            type
            handle
            fields {
              key
              type
              value
              reference {
                __typename
                ... on MediaImage {
                  image {
                    url
                    altText
                    width
                    height
                  }
                }
              }
            }
          }
        }
      }
    }
  }
`;
